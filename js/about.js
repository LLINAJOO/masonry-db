import { $, esc, shell } from "./common.js";
import { load } from "./data.js";
shell("about.html", "О проекте");

const main = $("#main");
main.innerHTML =
  `<h1>О проекте</h1><div class="about">` +
  `<p class="lead">Открытая база экспериментов по каменной кладке: результаты испытаний кирпича, раствора и кладки из научных статей — в одном месте и в единой форме.</p>` +
  `<h3>Как устроена база</h3><div class="three">` +
  `<div class="kv" style="--c:var(--blue)"><h4>Кладка</h4><p>Тип кладки, толщина шва, фото образца, схема испытания и кривая «сила — перемещение».</p></div>` +
  `<div class="kv" style="--c:#c4573a"><h4>Кирпич</h4><p>Тип, плотность, пустотность, удельный периметр и собственные испытания.</p></div>` +
  `<div class="kv" style="--c:var(--wait)"><h4>Раствор</h4><p>Плотность, модуль упругости, предельные деформация и напряжение, испытания.</p></div></div>` +
  `<h3>Как пользоваться</h3><ol>` +
  `<li><b>База данных → Каталог</b> — карточка записи: параметры кладки, кирпича и раствора, график F–Δ, фото кладки, схема испытания, сведения об источнике и скачивание данных.</li>` +
  `<li><b>База данных → Обзор</b> — все записи на одном графике с параллельными осями; выбранная запись подсвечена, а отбор задаёт поиск в таблице «Все записи».</li>` +
  `<li><b>Добавить эксперимент</b> — пошаговая форма: статья, кирпич, раствор, кладка. Фото и схемы можно приложить к кладке.</li></ol>` +
  `<h3>Проверка данных</h3><p>Новые заявки сначала попадают к администратору. В каталоге и обзоре видны только одобренные записи.</p>` +
  `<h3>Источники</h3><div id="src"><p class="hint">Загрузка…</p></div></div>`;
load()
  .then((rows) => {
    const src = [...new Set(rows.map((r) => r.src).filter((s) => s && s !== "—"))].sort();
    $("#src").innerHTML = src.length
      ? `<ul>${src.map((s) => `<li>${esc(s)}</li>`).join("")}</ul>`
      : `<p class="hint">Пока нет одобренных записей.</p>`;
  })
  .catch(
    (e) => ($("#src").innerHTML = `<div class="note">Не удалось загрузить: ${esc(e.message)}</div>`)
  );
